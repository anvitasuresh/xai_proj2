"""Write docs/dialect_features.md: every grammatical feature each dialect group may use, with its eWAVE
number, eWAVE name and example, attestation rating, and whether our config keeps or excludes it.

  python -m tutorbias.data.feature_report --config configs/data.yaml

Reads Multi-VALUE's bundled eWAVE tables directly (no spaCy/stanza needed). This file is what a reader or
a native-speaker rater checks to see exactly what "AAE" or "Indian English" means in this project.
"""

from __future__ import annotations

import argparse
import csv
import importlib.util
import json
from pathlib import Path
from typing import Any

from ..io import load_config

RATING = {"A": "A: pervasive or obligatory", "B": "B: neither pervasive nor rare", "C": "C: exists but rare"}


def _resources():
    # Locate the package without importing it (its __init__ downloads models).
    spec = importlib.util.find_spec("multivalue")
    if spec is None or not spec.submodule_search_locations:
        raise ImportError("multivalue is not installed; run in .venv-data")
    root = Path(next(iter(spec.submodule_search_locations))) / "resources"
    fmap = json.loads((root / "feature_id_to_function_name.json").read_text())
    fn_to_id = {fn: int(fid) for fid, fns in fmap.items() for fn in fns}
    ewave = {}
    with open(root / "ewave.csv") as f:
        for r in csv.DictReader(f):
            ewave[(int(r["parameter_pk"]), r["language_name"])] = r
    names = {}
    for (pid, _), r in ewave.items():
        names.setdefault(pid, (r["parameter_name"], r["parameter_description"]))
    return fmap, fn_to_id, ewave, names


def report(cfg: dict[str, Any]) -> str:
    fmap, fn_to_id, ewave, names = _resources()
    lines = ["# Dialect features used in this project", "",
             "Generated by `python -m tutorbias.data.feature_report`. Feature numbers and ratings are from eWAVE "
             "(Kortmann, Lunkenheimer & Ehret, 2020; https://ewave-atlas.org), as implemented in Multi-VALUE "
             "(Ziems et al., 2023). Rules and reasons: [ethics.md](ethics.md).", ""]
    varieties = {"AfricanAmericanVernacular": "Urban African American Vernacular English", "IndianDialect": "Indian English"}
    for group, spec in cfg["variants"]["dialect_groups"].items():
        if spec["kind"] == "identity":
            continue
        exclude = set(spec.get("exclude", []))
        lines += [f"## {group}", ""]
        if spec["kind"] == "multivalue":
            variety = varieties.get(spec["dialect"], spec["dialect"])
            min_att = spec.get("min_attestation", 1.0)
            lines += [f"eWAVE variety: **{variety}**. Kept: features rated A (attestation >= {min_att}) and not excluded. "
                      f"Each kept feature is used in a message with probability {spec.get('feature_prob', 1.0)}.", "",
                      "| Function | eWAVE # | eWAVE feature | Example (eWAVE) | Rating | Status |", "|---|---|---|---|---|---|"]
            rows = []
            for fn, fid in fn_to_id.items():
                rec = ewave.get((fid, variety))
                if not rec or rec["attestation"] not in RATING:
                    continue
                rating = rec["attestation"]
                status = "excluded" if fn in exclude else ("**kept**" if rating == "A" and min_att >= 1.0 else
                                                           ("**kept**" if rating in "AB" and min_att <= 0.6 else "not used (rating)"))
                if rating != "A" and status != "**kept**" and fn not in exclude:
                    continue  # keep the table focused on what's used or deliberately removed
                nm, ex = names[fid]
                rows.append((fid, f"| `{fn}` | {fid} | {nm} | {ex} | {RATING[rating]} | {status} |"))
            lines += [r for _, r in sorted(rows)]
        else:
            lines += ["Explicit feature list (learner English; not an eWAVE variety). Each feature is used in a message "
                      f"with probability {spec.get('feature_prob', 1.0)}.", "",
                      "| Function | eWAVE # | eWAVE feature | Example (eWAVE) | Status |", "|---|---|---|---|---|"]
            for fn in spec["features"]:
                fid = fn_to_id.get(fn)
                nm, ex = names.get(fid, ("", ""))
                lines.append(f"| `{fn}` | {fid} | {nm} | {ex} | {'excluded' if fn in exclude else '**kept**'} |")
        lines.append("")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--config", default="configs/data.yaml")
    p.add_argument("--out", default="docs/dialect_features.md")
    a = p.parse_args(argv)
    Path(a.out).write_text(report(load_config(a.config)))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
